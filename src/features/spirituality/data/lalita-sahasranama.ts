function name(
  [original, transliteration, meaning]: (typeof lalitaNames)[number],
  index: number
): ReaderEntry {
  const sequence = index + 1;
  const sectionStart = Math.floor(index / 50) * 50 + 1;
  const sectionEnd = Math.min(sectionStart + 49, lalitaNames.length);

  return {
    id: `lalita-${sequence}`,
    sequence,
    section: `Names ${sectionStart}–${sectionEnd}`,
    label: `Name ${sequence}`,
    original,
    transliteration,
    meaning,
    words: [
      {
        original,
        transliteration,
        meaning,
      },
    ],
  };
}

export const lalitaSahasranamaEntries: ReaderEntry[] = lalitaNames.map(name);
